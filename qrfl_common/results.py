"""Emit machine-readable results and LaTeX macros for manuscript inclusion."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parents[1]
RESULTS_DIR = ROOT / "results"


def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def load_config(name: str) -> dict[str, Any]:
    config_path = ROOT / "configs" / name
    with config_path.open("r", encoding="utf-8") as handle:
        return yaml.safe_load(handle)


# LaTeX control words may contain letters only, so numeric parameter labels
# (ML-KEM-768, ML-DSA-65, ...) must be spelled out to stay addressable.
_DIGIT_WORDS = {
    "0": "Zero",
    "1": "One",
    "2": "Two",
    "3": "Three",
    "4": "Four",
    "5": "Five",
    "6": "Six",
    "7": "Seven",
    "8": "Eight",
    "9": "Nine",
}


def latex_macro_name(name: str) -> str:
    """Convert an arbitrary label into a letters-only LaTeX control word."""
    out = []
    for char in name:
        if char.isalpha() and char.isascii():
            out.append(char)
        elif char in _DIGIT_WORDS:
            out.append(_DIGIT_WORDS[char])
    sanitized = "".join(out)
    if not sanitized:
        raise ValueError(f"macro name {name!r} contains no usable characters")
    return sanitized


class ResultsEmitter:
    """Collect numeric outputs and write results_macros.tex.

    Macros persist in ``results/macros.json`` so that pipeline stages run in any
    order, or individually, without discarding macros emitted by other stages.
    """

    STORE_NAME = "macros.json"

    def __init__(self, results_dir: Path | None = None) -> None:
        self.results_dir = ensure_dir(results_dir or RESULTS_DIR)
        self.macros: dict[str, str] = {}
        self.metadata: dict[str, Any] = {}

    @property
    def store_path(self) -> Path:
        return self.results_dir / self.STORE_NAME

    def _load_store(self) -> dict[str, str]:
        if not self.store_path.exists():
            return {}
        try:
            with self.store_path.open("r", encoding="utf-8") as handle:
                data = json.load(handle)
        except (json.JSONDecodeError, OSError):
            return {}
        return {str(k): str(v) for k, v in data.items()} if isinstance(data, dict) else {}

    def set_macro(self, name: str, value: str | float | int, fmt: str | None = None) -> None:
        if fmt is not None:
            rendered = format(value, fmt)
        elif isinstance(value, float):
            rendered = f"{value:.4f}"
        else:
            rendered = str(value)
        self.macros[latex_macro_name(name)] = rendered

    def remove_macro(self, name: str) -> None:
        key = latex_macro_name(name)
        self.macros.pop(key, None)
        store = self._load_store()
        store.pop(key, None)
        with self.store_path.open("w", encoding="utf-8") as handle:
            json.dump(store, handle, indent=2, sort_keys=True)

    def save_json(self, rel_path: str, payload: Any) -> Path:
        out = ensure_dir(self.results_dir / Path(rel_path).parent)
        target = self.results_dir / rel_path
        with target.open("w", encoding="utf-8") as handle:
            json.dump(payload, handle, indent=2, default=str)
        return target

    def save_csv(self, rel_path: str, dataframe) -> Path:
        out = ensure_dir(self.results_dir / Path(rel_path).parent)
        target = self.results_dir / rel_path
        dataframe.to_csv(target, index=False)
        return target

    def write_macros(self, filename: str = "results_macros.tex") -> Path:
        merged = self._load_store()
        merged.update(self.macros)

        with self.store_path.open("w", encoding="utf-8") as handle:
            json.dump(merged, handle, indent=2, sort_keys=True)

        target = self.results_dir / filename
        lines = [
            "% Auto-generated by QRFL reproducibility pipeline. Do not edit by hand.",
            "% \\input{qrfl-artifacts/results/results_macros.tex}",
            "",
        ]
        # \providecommand keeps the manuscript compilable when a stage has not
        # run yet; \renewcommand then installs the measured value.
        for key in sorted(merged):
            lines.append(f"\\providecommand{{\\{key}}}{{\\QRFLMissing}}")
            lines.append(f"\\renewcommand{{\\{key}}}{{{merged[key]}}}")
        with target.open("w", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")
        return target

    def merge(self, other: "ResultsEmitter") -> None:
        self.macros.update(other.macros)
        self.metadata.update(other.metadata)
